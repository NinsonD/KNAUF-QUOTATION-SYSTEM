import assert from 'node:assert/strict';
import { browserDraftKey, duplicateQuotation, parseBrowserDraft } from '../src/lib/quotation/drafts';
import { calculateQuotation } from '../src/lib/engine/calculator';
import systems from '../src/data/knauf-systems.json';
import type { CalculatedItem, KnaufSystemDefinition } from '../src/lib/engine/types';

const material: CalculatedItem = { id: 'original-item', productName: 'Test material', unit: 'pcs', factorPerM2: 2, factorOverridden: true, totalQuantity: 200, unitPriceAed: 7, totalPriceAed: 1400, isHeadDeflection: false };
const meta = { quoteNumber: 'NEW-REF', date: '14/10/2026', projectName: '', clientName: '', salesman: '', status: 'DRAFT' as const };
const source = { calculationVersion: 'workbook', clientName: 'Customer', projectName: 'Project', salesman: 'Estimator', items: [material, { ...material, isHeadDeflection: true }] };
const copy = duplicateQuotation(source, meta);
assert.equal(copy.meta.quoteNumber, 'NEW-REF');
assert.equal(copy.meta.date, meta.date);
assert.equal(copy.meta.status, 'DRAFT');
assert.equal(copy.meta.clientName, source.clientName);
assert.equal(copy.customItems.base[0].unitPriceAed, 7);
assert.equal(copy.customItems.deflection.length, 1);
assert.ok(!('id' in copy.customItems.base[0]));
copy.customItems.base[0].unitPriceAed = 11;
assert.equal(source.items[0].unitPriceAed, 7, 'Copy must not mutate original');
assert.throws(() => duplicateQuotation({ ...source, calculationVersion: 'legacy' }, meta));
assert.notEqual(browserDraftKey('admin'), browserDraftKey('estimator'));
assert.notEqual(browserDraftKey('admin'), browserDraftKey('admin', 'original'));
const draft = { version: 1, systemCode: 'KW111', scale: 123, includeDeflection: true, prices: { 'Test material': 11 }, technicalParameters: {}, customItems: copy.customItems, meta: copy.meta };
assert.deepEqual(parseBrowserDraft(JSON.stringify(draft)), draft);
assert.throws(() => parseBrowserDraft('{broken'));
assert.throws(() => parseBrowserDraft(JSON.stringify({ ...draft, version: 99 })));
assert.throws(() => parseBrowserDraft(JSON.stringify({ ...draft, prices: { a: 'wrong' } })));
assert.throws(() => parseBrowserDraft(JSON.stringify({ ...draft, meta: { ...meta, projectName: null } })));
const system = systems.find(value => value.code === 'KW111') as KnaufSystemDefinition;
const restored = parseBrowserDraft(JSON.stringify(draft));
const before = calculateQuotation(system, draft.scale, draft.prices, true, draft.customItems);
const after = calculateQuotation(system, restored.scale, restored.prices, true, restored.customItems);
assert.deepEqual(after, before, 'Draft restoration must preserve calculated quantities and rates');
console.log('Quotation copy isolation, fresh reference, account-scoped drafts, invalid draft handling and restored calculation tests passed.');
